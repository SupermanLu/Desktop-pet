    @staticmethod
    def _period() -> str:
        h = datetime.now().hour
        if 5 <= h < 9:
            return "early"      # 清晨
        if 9 <= h < 12:
            return "morning"    # 上午
        if 12 <= h < 14:
            return "noon"       # 中午
        if 14 <= h < 18:
            return "afternoon"  # 下午
        if 18 <= h < 23:
            return "evening"    # 晚上
        return "night"          # 深夜

