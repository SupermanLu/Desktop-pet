    # ---------- 回复 ----------
    def reply(self, text: str) -> str:
        text = (text or "").strip()
        if not text:
            return f"嗯？我在这里哦～ {self.pet_name}一直陪着你 👀"

        # 时间感知：问候叠加
        greeting = self._time_greeting(text)

        for keywords, replies in self._rules:
            if not keywords:
                break
            for kw in keywords:
                if kw in text:
                    return random.choice(replies)
        # 兜底
        return random.choice(self._rules[-1][1])

    def _time_greeting(self, text: str) -> str:
        """早上好/下午好/晚上好/晚安 按时段给出对应回复。"""
        period = self._period()
        if "早上" in text or "早安" in text:
            return "早呀～新的一天，记得先喝杯温水 ☀️💧"
        if "中午" in text or "午安" in text:
            return "中午好呀！记得按时吃午饭，别饿着肚子忙活 🍚"
        if "下午" in text:
            return "下午好～下午茶时间到，起来活动活动？🍵"
        if "晚上" in text:
            return "晚上好～今天也辛苦啦，注意眼睛休息哦 🌆"
        if "晚安" in text or "睡觉" in text:
            return "晚安～把工作放一放，好好睡觉，明天再战 🌙💤"
        if period == "early":
            return "早呀～清晨是好时光，但先喝口水提提神 ☀️"
        if period == "morning":
            return "早上好呀～新的一天，元气满满！✨"
        if period == "noon":
            return "中午好！到饭点了，记得先去吃饭哦 🍚"
        if period == "afternoon":
            return "下午好～久坐记得起来动一动，眼睛也要休息 🌿"
        if period == "evening":
            return "晚上好～今天辛苦了，注意别太晚哦 🌆"
        return "夜深啦～还在忙吗？记得早点休息 🌙"
