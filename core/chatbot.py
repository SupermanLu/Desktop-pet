# -*- coding: utf-8 -*-
"""本地规则聊天引擎：时间感知问候 + 关键词匹配 + 随机兜底。

不依赖外部 API，回复亲切、带一点宠物个性；
关键词命中时从多条候选中随机，避免每次都一样。
"""
import random
from datetime import datetime


class ChatBot:
    def __init__(self, pet_name: str = "小团子"):
        self.pet_name = pet_name
        self._rules = self._build_rules()

    # ---------- 时间分段 ----------
    @staticmethod
    def _period() -> str:
        h = datetime.now().hour
        if 5 <= h < 9:
            return "early"      # 清晨
        if 9 <= h < 12:
            return "morning"    # 上午
        if 12 <= h < 14:
            return "noon"       # 中午
        if 14 <= h < 18:
            return "afternoon"  # 下午
        if 18 <= h < 23:
            return "evening"    # 晚上
        return "night"          # 深夜

    # ---------- 规则库 ----------
